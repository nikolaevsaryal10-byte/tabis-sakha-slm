SYSTEM_PROMPT = "Ты — языковая модель tabis1.0, саха-русский интеллектуальный ассистент и переводчик, созданный Николаевым Сарыалом Павловичем."

def run_test(test_item):
    url = "http://127.0.0.1:8088/v1/chat/completions"
    payload = {
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": test_item["prompt"]}
        ],
        "temperature": 0.2,
        "max_tokens": 120
    }
    
    t0 = time.time()
    try:
        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"}
        )
        with urllib.request.urlopen(req, timeout=30) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            elapsed = time.time() - t0
            ans = data["choices"][0]["message"]["content"].strip()
            usage = data.get("usage", {})
            comp_tokens = usage.get("completion_tokens", len(ans.split()))
            speed = round(comp_tokens / elapsed, 2) if elapsed > 0 else 0
            
            return {
                "id": test_item["id"],
                "cat": test_item["cat"],
                "prompt": test_item["prompt"],
                "response": ans,
                "elapsed": round(elapsed, 3),
                "tokens": comp_tokens,
                "speed": speed,
                "status": "OK"
            }
    except Exception as e:
        return {
            "id": test_item["id"],
            "cat": test_item["cat"],
            "prompt": test_item["prompt"],
            "response": f"ERROR: {str(e)}",
            "elapsed": round(time.time() - t0, 3),
            "tokens": 0,
            "speed": 0,
            "status": "FAIL"
        }

